export function joinPath(folder, file) {
  // Build an absolute path from the site root (using Vite's configured base)
  // instead of a relative one — a relative path resolves against whatever
  // the current document URL happens to be, which breaks under GitHub Pages'
  // subpath hosting if the URL is ever missing its trailing slash.
  const base = import.meta.env.BASE_URL.replace(/\/+$/, "");
  const f = (folder || "").replace(/^\/+/, "").replace(/\/+$/, "");
  const g = String(file).replace(/^\/+/, "");
  const path = f ? f + "/" + g : g;
  return base + "/" + path;
}

/**
 * Small WebP version of a picture, generated by scripts/thumbs.mjs into
 * public/thumbs. Videos have no thumbnail. Use with `thumbFallback` so a
 * missing thumbnail falls back to the original.
 */
export function thumbPath(folder, file) {
  if (isVideo(file)) return joinPath(folder, file);
  const f = (folder || "").replace(/^\/+/, "").replace(/^pictures\/?/, "");
  return joinPath("thumbs/" + f, String(file).replace(/\.[^.]+$/, ".webp"));
}

/** onError handler: swap a failed thumbnail for the original file once. */
export function thumbFallback(original) {
  return (e) => {
    const img = e.currentTarget;
    if (img.dataset.fallback) return;
    img.dataset.fallback = "1";
    img.src = original;
  };
}

export function flagSrc(iso) {
  if (!iso || iso.length !== 2) return null;
  return "https://flagcdn.com/" + iso.toLowerCase() + ".svg";
}

export function formatDateRange(start, end) {
  if (!start && !end) return "";
  const s = start ? new Date(start) : null;
  const e = end ? new Date(end) : null;
  const opts = { year: "numeric", month: "short", day: "numeric" };
  const loc = "nl-NL";
  if (s && e) {
    if (s.getFullYear() === e.getFullYear() && s.getMonth() === e.getMonth()) {
      return `${s.getDate()}–${e.getDate()} ${s.toLocaleDateString(loc, { month: "short" })} ${s.getFullYear()}`;
    }
    return `${s.toLocaleDateString(loc, opts)} – ${e.toLocaleDateString(loc, opts)}`;
  }
  return (s || e).toLocaleDateString(loc, opts);
}

/** Short handwritten-style caption date: "aug 2026" */
export function formatMonthYear(date) {
  if (!date) return "";
  return new Date(date).toLocaleDateString("nl-NL", { month: "short", year: "numeric" }).replace(".", "");
}

/** Inclusive number of days between start and end; null when either is missing. */
export function tripDays(v) {
  if (!v.startDate || !v.endDate) return null;
  const ms = new Date(v.endDate) - new Date(v.startDate);
  if (Number.isNaN(ms) || ms < 0) return null;
  return Math.round(ms / 86400000) + 1;
}

export function formatDays(n) {
  if (!n) return "";
  return n === 1 ? "1 dag" : `${n} dagen`;
}

/** Named stops of a route, in order. */
export function routeStops(v) {
  if (!v.route || v.route.length < 2) return [];
  return v.route.map((p) => p.name || "").filter(Boolean);
}

export function isVideo(file) {
  return /\.(mp4|webm|mov)$/i.test(String(file));
}

/** Human caption for a photo instead of the raw WhatsApp filename. */
export function photoCaption(v, index, total) {
  const when = formatMonthYear(v.startDate);
  return `${v.title}${v.location ? ", " + v.location : ""}${when ? " · " + when : ""} (${index + 1}/${total})`;
}

export function tripCountryCodes(v) {
  return Array.isArray(v.countries) ? v.countries : v.country ? [v.country] : [];
}

export function visitedCountrySet(vacations) {
  const set = new Set();
  vacations.forEach((v) => tripCountryCodes(v).forEach((c) => set.add(c.toUpperCase())));
  return set;
}

/** Distance in km between two lat/lon points. */
export function distanceKm(a, b) {
  const R = 6371;
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLon = toRad(b.lon - a.lon);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

/**
 * Group trips whose main point lies within `radiusKm` of each other, so repeat
 * visits (five times Oslo) become one marker with a count instead of a stack
 * where only the top one can be clicked. Input must be sorted newest first;
 * the group keeps that order and sits at the newest trip's coordinates.
 */
export function groupByPlace(vacations, radiusKm = 15) {
  const groups = [];
  vacations.forEach((v) => {
    if (typeof v.lat !== "number" || typeof v.lon !== "number") return;
    const g = groups.find((grp) => distanceKm(grp, v) <= radiusKm);
    if (g) g.trips.push(v);
    else groups.push({ id: v.id, lat: v.lat, lon: v.lon, trips: [v] });
  });
  return groups;
}

/** "3e bezoek" style label: how many times this place was visited up to and including this trip. */
export function visitIndex(v, group) {
  if (!group || group.trips.length < 2) return null;
  const chronological = group.trips.slice().reverse();
  return { n: chronological.findIndex((t) => t.id === v.id) + 1, total: group.trips.length };
}
